<?php
/**
 * User-initiated feedback for the learning loop.
 *
 * FCK Malware has no server and collects nothing on its own. Administrators
 * can choose to:
 *   - open a pre-filled GitHub issue reporting a false positive or a
 *     confirmed infection (they see the full text before submitting);
 *   - export an anonymous statistics bundle (per-signature counts of
 *     detections, ignores, quarantines) and attach it to an issue.
 *
 * Reports contain no site URL, no user data and no file contents unless the
 * administrator ticks "include excerpt", in which case a short redacted
 * excerpt is added. Maintainers turn reports into proposals with
 * tools/intel/learn.php; nothing changes in the shipped signatures without
 * review, testing and approval.
 *
 * @package Fckmaleware
 */

namespace Fckmaleware;

final class Feedback {

	public const REPOSITORY = 'rakibchbd/fckmaleware';
	private const ID_OPTION = 'fckmw_feedback_id';

	/** Random identifier so a maintainer can tell bundles from the same site apart; not derived from the site. */
	public static function anonymous_id(): string {
		$id = (string) Store::get( self::ID_OPTION, '' );
		if ( ! preg_match( '/^[a-f0-9]{16}$/', $id ) ) {
			$id = bin2hex( random_bytes( 8 ) );
			Store::set( self::ID_OPTION, $id );
		}
		return $id;
	}

	/**
	 * Anonymized description of where a finding lives: public components
	 * (wordpress.org plugins, core) are named; private code is not.
	 */
	public static function component( array $finding, Plugin $plugin ): array {
		if ( 'file' !== $finding['object_type'] ) {
			return array( 'component' => $finding['object_type'], 'path' => '' );
		}
		$file = (string) $finding['file'];
		if ( 0 !== strpos( $file, 'wp-content/' ) && Paths::is_core( $file ) ) {
			return array( 'component' => 'core@' . ( $GLOBALS['wp_version'] ?? '' ), 'path' => $file );
		}
		$integrity = new Detection\IntegrityLayer( $plugin->checksums(), $plugin->baseline(), false, false );
		$component = $integrity->component( $file );
		if ( null !== $component && 0 === strpos( $component[0], 'plugin:' ) && '' !== $component[1] && null !== $plugin->checksums()->plugin( substr( $component[0], 7 ), $component[1] ) ) {
			return array( 'component' => $component[0] . '@' . $component[1], 'path' => $component[2] );
		}
		$kind = null === $component ? 'other' : explode( ':', $component[0] )[0];
		return array( 'component' => '[private ' . $kind . ']', 'path' => '[' . pathinfo( $file, PATHINFO_EXTENSION ) . ' file]' );
	}

	/**
	 * GitHub "new issue" URL with a pre-filled, anonymized report.
	 *
	 * @param string $type false_positive | confirmed
	 */
	public static function issue_url( array $finding, string $type, bool $include_excerpt, Plugin $plugin ): string {
		$where = self::component( $finding, $plugin );
		$lines = array(
			'<!-- Generated by FCK Malware. Review before submitting; remove anything you do not want to share. -->',
			'**Report:** ' . ( 'confirmed' === $type ? 'confirmed malware (missed or correct detection)' : 'false positive' ),
			'**Detection:** `' . $finding['signature_id'] . '` ' . $finding['signature_name'],
			'**Layer / verdict:** ' . $finding['source'] . ' / ' . $finding['verdict'] . ' (' . $finding['confidence'] . '%)',
			'**Component:** ' . $where['component'],
			'**Path in component:** ' . ( '' !== $where['path'] ? '`' . $where['path'] . '`' : 'n/a' ),
			'**SHA-256:** `' . ( '' !== $finding['file_hash'] ? $finding['file_hash'] : 'n/a' ) . '`',
			'**Plugin / signatures:** ' . FCKMW_VERSION . ' / ' . $plugin->signatures()->version(),
			'**Reporter id (random):** ' . self::anonymous_id(),
		);
		if ( $include_excerpt && '' !== (string) $finding['excerpt'] ) {
			$excerpt = substr( Ai\Redactor::redact( (string) $finding['excerpt'] ), 0, 400 );
			$lines[] = '';
			$lines[] = '**Excerpt (redacted):**';
			$lines[] = '```';
			$lines[] = str_replace( '```', '` ` `', $excerpt );
			$lines[] = '```';
		}
		$lines[] = '';
		$lines[] = '**Notes:** ';

		$title = ( 'confirmed' === $type ? 'Confirmed malware: ' : 'False positive: ' ) . $finding['signature_id'];
		return 'https://github.com/' . self::REPOSITORY . '/issues/new?' . http_build_query(
			array(
				'title'  => $title,
				'labels' => 'confirmed' === $type ? 'confirmed-malware' : 'false-positive',
				'body'   => implode( "\n", $lines ),
			),
			'',
			'&',
			PHP_QUERY_RFC3986
		);
	}

	/** Anonymous per-signature statistics (what a site may choose to share). */
	public static function stats_bundle( Plugin $plugin ): array {
		global $wpdb;
		$table = Findings::table();
		$rows  = $wpdb->get_results( "SELECT signature_id, status, COUNT(*) AS n FROM {$table} GROUP BY signature_id, status", ARRAY_A ); // phpcs:ignore WordPress.DB
		$stats = array();
		foreach ( (array) $rows as $row ) {
			$id = (string) $row['signature_id'];
			if ( 0 === strpos( $id, 'IMUNIFY:' ) ) {
				$id = 'IMUNIFY';
			}
			$stats[ $id ]                    = $stats[ $id ] ?? array( 'open' => 0, 'ignored' => 0, 'quarantined' => 0, 'resolved' => 0 );
			$stats[ $id ][ $row['status'] ] += (int) $row['n'];
		}
		ksort( $stats );
		return array(
			'format'          => 'fckmw-feedback-1',
			'reporter'        => self::anonymous_id(),
			'generated'       => gmdate( 'c' ),
			'plugin'          => FCKMW_VERSION,
			'signatures'      => $plugin->signatures()->version(),
			'wordpress'       => $GLOBALS['wp_version'] ?? '',
			'signature_stats' => $stats,
		);
	}
}
